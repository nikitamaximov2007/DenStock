"""Единая свёртка названия детали для поиска. Одна на весь проект.

Зачем отдельная свёртка, а не `__icontains`
-------------------------------------------

`__icontains` на PostgreSQL превращается в `UPPER(x) LIKE UPPER(y)`, а `UPPER`
считает регистр по локали КЛАСТЕРА. Кластер, созданный с локалью `C`, кириллицу
не трогает вовсе: там `upper('прокладка')` это `'прокладка'`. Проверено на
PostgreSQL 16:

    locale en_US.utf8 -> upper('прокладка') = 'ПРОКЛАДКА'
    locale C          -> upper('прокладка') = 'прокладка'

То есть на таком кластере поиск по русскому названию становится
регистрозависимым: «прокладка» не находит «Прокладка головки блока», а опечатка
«проклатка» не находит ничего, потому что триграммы строчного запроса не
пересекаются с триграммами названия с заглавной буквы. То же самое на SQLite,
где `LIKE` регистронезависим только для ASCII.

Поэтому регистр сворачивается в Python (`str.casefold`, правила Unicode, от
локали базы не зависят), результат хранится рядом с названием, а поиск идёт по
уже свёрнутой колонке обычным `=`, `LIKE` и триграммами. Так одинаково ведут
себя PostgreSQL любой локали и SQLite, и так же устроены уже существующие
поисковые формы проекта: `PartNumber.normalized_value` для номеров и
`Customer.phone_normalized` для телефонов.

«ё» и «е»
---------

Одно и то же название пишут и «щёткой», и «щеткой». Различать их в поиске
незачем: буквы взаимозаменяемы в бытовом письме, и человек не обязан помнить,
как записал название оператор. Свёртка приводит «ё» к «е» с обеих сторон -
и в сохранённом названии, и в запросе, - поэтому находится любая комбинация.
Ничего, кроме регистра, «ё» и повторяющихся пробелов, свёртка не меняет: это
не транслитерация, не стемминг и не исправление опечаток.
"""

YO = "ё"
YE = "е"


def fold_search_text(value: str | None) -> str:
    """Свёрнутая форма названия для поиска. Пусто, если текста нет.

    Регистр по правилам Unicode, «ё» = «е», лишние пробелы убраны. Одна и та же
    функция применяется к сохранённому названию и к тому, что набрал человек:
    сравнивать можно только одинаково свёрнутые строки.
    """
    return " ".join((value or "").split()).casefold().replace(YO, YE)
