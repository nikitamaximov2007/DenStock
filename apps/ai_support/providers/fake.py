from .base import SupportRequest, SupportResult


class FakeProvider:
    """Deterministic provider used only when tests explicitly enable it."""

    def generate(self, request: SupportRequest) -> SupportResult:
        body = "\n\n".join(request.knowledge_chunks).lower()
        if "ssl_protocol_error" in request.user_text.lower() or "голому ip" in body:
            base_url = request.public_base_url or "канонический адрес не настроен"
            text = (
                "Ошибка обычно появляется при открытии HTTPS по голому IP. "
                "Сначала проверьте список продаж: есть ли документ, проведена ли "
                "продажа, изменились ли остатки и нет ли дубля. Затем откройте "
                "«Склад» - «История»: операция могла завершиться до ошибки браузера. "
                "Не нажимайте «Провести продажу» повторно, пока не исключили дубль.\n\n"
                f"Затем откройте DenisStock по каноническому адресу: {base_url}. "
                "Если ошибка повторится и там, создайте обращение с точным текстом ошибки."
            )
        elif "инвентар" in request.user_text.lower() or "пересч" in request.user_text.lower():
            text = (
                "Для начала откройте «Склад» - «Инвентаризация» и выберите режим. "
                "Для первичного ввода содержимого ячейки откройте «Инвентаризация "
                "ячейки».\n\n"
                "1. Нажмите «Новый пересчёт».\n"
                "2. Заполните адрес и нажмите «Начать пересчёт».\n"
                "3. Отсканируйте все детали и проверьте столбец «Количество».\n"
                "4. Нажмите «Завершить пересчёт».\n"
                "5. Нажмите «Создать черновик документа».\n"
                "6. После проверки нажмите «Провести инвентаризацию».\n\n"
                "Остатки не меняются во время сканирования или в черновике. Они "
                "появятся только после проведения. Если остаток уже есть и его нужно "
                "привести к факту, используйте вкладку «Сверочные документы»."
            )
        elif "поступ" in request.user_text.lower() or "принять" in request.user_text.lower():
            text = (
                "Откройте «Склад» - «Поступление» и нажмите «Новое поступление». "
                "Заполните поставщика и дату, добавьте позиции с количеством, ценой и "
                "ячейкой, затем нажмите «Провести поступление». До проведения остатки "
                "не изменятся."
            )
        else:
            text = "Уточните, на каком экране DenisStock вы находитесь и что хотите сделать?"
        return SupportResult(
            text=text,
            provider="fake",
            model="fake-support-model",
            status="completed",
            latency_ms=1,
            usage={"input_tokens": 20, "output_tokens": 80},
            request_id="fake-request",
        )
